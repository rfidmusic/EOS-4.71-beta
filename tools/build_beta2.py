#!/usr/bin/env python3
"""EOS 4.71-beta2: the frozen LP+Fuzz release (build_lpfuzz.py --release) plus Sample Edit "Insert Silence"
(patches/silence/silence.s, notes/silence_insert.md) and the cord destination "'Slice" (patches/slice/slice.s,
notes/slice_design.md).

usage: build_beta2.py BASE.bin OUT.bin [--probe]   (BASE = build/eos471_beta.bin; writes OUT.bin.syms.json)
--probe: diagnostic "EOS 4.71-b2 SliceProbe": no Insert Silence; patches/slice/probe.s records slice_exit's inputs
(parameter 195 = halfword index / value).

Space (all proven unused; notes/slice_design.md):
  A 0xEB306-0xEB414  AudioAnalyzer debug strings (only use: pea for the trace stub 0xE939C = rts) + orphan rts/nop
  B 0x98F86-0x98FD8  graphics error strings (only use: pea for the stub 0x3A454 = rts)
  C 0x9B788-0x9B7A4  "LCD not ready - timed out" (only use: pea for 0x3A454)
  F filter-registry region after the LP+Fuzz code (NOP fill)
  V16 0x20240-0x20260, V48 0x202C0-0x20300: reserved exception vectors 16-23 and 48-63 (never generated by the
  5206e); U 0x203D0-0x20400: user interrupt vectors 116-127 (not programmed). All = the fatal default handler.
Every pea of a removed string becomes subq.l #4,sp ; nop ; nop (same stack, flags untouched; the stub ignores it).
Patches: Sample Edit Utils I slot 0xA4AB0 -> Insert Silence; Paste exec pointer 0xFB8E2 -> paste_wrap;
0x61B9C jmp sl_mode; 0x5FBA6 / 0x5FECA jsr shift_w; 0x5FD2C jmp slice_exit; 0x5F914 jsr pit_hook;
Plugin port-map builders 0x15EF5C/0x15F3E0 -> patches/portmap/portmap.s (table-driven; pointer 0x15FAD4 -> pm_B),
freeing ~2 KB after it (NOP fill), which holds the Beat Munger "Slice" key (patches/slicer/slicer.s, soft-key slot
0xB71F2 between Cancel and Stop; notes/slicer_design.md).
Tick loop-shift glide: 0x5FECA jsr shift_t, 0x5FED0..0x5FEED -> patches/slpscn/slew.s (max LIM samples per tick). destination 55 -> "'Slice" (0x1C, 0x0100);
destination 58 renamed SLpScn -> WTScan (same length, in place);
HP2/HP4/Contrary BP word 9 lowered with Q (patches/hpgain/hpgain.s, K in descriptor byte 15);
pan table 0x61590 entries 63/64 -322/-311 -> -316/-316: centre pan balanced (was 1 step = ~0.24 dB right-heavy).
RFX pan table 0x10E794 (stock: a copy of 0x61590, but indexing 0x10E504's 0.375 dB steps, so centre was -7.5 dB and
one step right-heavy) -> the fixed main law scaled to RFX units, (t * 105) >> 8, entry 0 kept -4096 (silent): hard pan
0 dB as before, centre -3.0 dB both sides, matching the main outputs (notes/rfx_mix.md).
"""
import json, os, struct, subprocess, sys, tempfile, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import eos_lz            # noqa: E402
import build_lpfuzz      # noqa: E402

ROOT = os.path.dirname(HERE)
SIL, SLC = os.path.join(ROOT, 'patches', 'silence'), os.path.join(ROOT, 'patches', 'slice')
PMD = os.path.join(ROOT, 'patches', 'portmap')
SLR = os.path.join(ROOT, 'patches', 'slicer')
HPG = os.path.join(ROOT, 'patches', 'hpgain')
BIN = '/opt/homebrew/bin/'
BASE = 0x20000
NAME = b'EOS 4.71-beta2 build 2'
DEFAULT_VEC = 0x20926
REGION_END = 0x683F0
MENU, EXEC_PTR, PASTE = 0xA4AB0, 0xFB8E2, 0xF79D4
A, B_, C = (0xEB306, 0xEB414), (0x98F86, 0x98FD8), (0x9B788, 0x9B7A4)
V16, V48, U48 = (0x20240, 0x20260), (0x202C0, 0x20300), (0x203D0, 0x20400)
# pea site -> string it pushes (all inside A, B or C)
PEAS = {0xEB19C: 0xEB308, 0xE8AD6: 0xEB32C, 0xE8C68: 0xEB344, 0xE8C82: 0xEB350, 0xE8E28: 0xEB370,
        0xE8E50: 0xEB38C, 0xE8FDC: 0xEB3A8, 0xE911A: 0xEB3B4, 0xE914E: 0xEB3C8, 0xE915E: 0xEB3EC,
        0xE91D2: 0xEB404, 0x97026: 0x98F88, 0x9707E: 0x98F98, 0x972EC: 0x98FA8, 0x97342: 0x98FB4,
        0x9AE58: 0x9B788}
STRINGS = {0xEB308: b'TheBeatData->DownBeatCand[i] %d\n', 0xEB404: b'%.2f %.2f \n', 0x98F88: b'Bad screen id',
           0x98FB4: b'Unbalanced calls to GrEnableUpdate', 0x9B788: b'LCD not ready - timed out'}
HOOKS = {0x61B9C: ('4ef9000204d8', 'jmp', 'sl_mode'), 0x5FBA6: ('4eb900020080', 'jsr', 'shift_w'),
         0x5FECA: ('4eb900020080', 'jsr', 'shift_t'), 0x5FD2C: ('4cd734c04fef0014', 'jmp', 'slice_exit'),
         0x5F914: ('3229000a30280038', 'jsr', 'pit_hook')}
DEST_TABLE, SLICE_CODE = 0x6344C, 55
# loop-shift glide: the tick's apply code after the shift call (patches/slpscn/slew.s, shift_t in slice.s)
SLEW_AT, SLEW_STOCK = 0x5FED0, '4e714e714e714e714e71322d002c48c1b2876740200790812200' + '3b47002c'
SNAP_AT = 0x200EC   # (old frame-stepping experiment; not applied)
DESC195 = 0x25AF4
PM, PM_CRC, PM_PA, PM_PB = (0x15EF5C, 0x15F818), 0x8076C4B4, 0x15FAC4, 0x15FAD4
PM_PA_TARGET = 0x15EF5C
PAN_TAB = 0x61590                         # pan gain table (128 words, read only by 0x60784): entries 63/64
PAN_FIX = ((-322, -311), (-316, -316))   # stock -> equal, so centre (index 64 reads 64 and 63) is balanced
RFX_PAN = 0x10E794                        # RFX send pan table (128 words), read only by 0x10E280 (movea.l below)
RFX_PAN_REF = (0x10E2FE, '2a7c0010e794')  # movea.l #$10e794,a5: the table's only reference
HPG_CF, HPG_CF_STOCK = 0x667CE, '203910004d7c21400024'   # HP/BP common_cf: word 9 = base gain
HPG_PQ, HPG_PQ_STOCK = 0x6680C, '0281000000ff'           # HP/BP common_pq: andi.l #0xFF,d1
HPG_K = {0x660E0: 32, 0x66A40: 48, 0x66A8C: 16}          # descriptor byte 15 (HP2, HP4, Contrary BP): word-9 cut K (HP4 48 after re-measure)
SCN_NAME = 0x2012E                        # destination 58's name (lfosync.s name_scn): 'SLpScn' -> 'WTScan'
BM_KEYS, BM_SLOT = 0xB71E2, 0xB71F2      # Beat Munger soft keys {name, handler}; 0xB71F2 is the empty one
NOP_SUBQ = bytes.fromhex('598f4e714e71')


def u32(img, a):
    return struct.unpack('>I', img[a - BASE:a - BASE + 4])[0]


def portmap_rows(img):
    """Decode the stock port-map builders' rows (idx, first value, count) into patches/portmap/rows.inc.
    Generated at build time from the base image (E-mu data: not kept in the repository)."""
    lines = ['| generated by build_beta2.py from the base image: idx, first value, count (values step by 2, rest -1)']
    for nm, start in (('tabA', 0x15EF5C), ('tabB', 0x15F3E0)):
        a, cur, rows = start + 12, [], []
        while True:
            w = struct.unpack('>H', img[a - BASE:a - BASE + 2])[0]
            if img[a - BASE:a - BASE + 6].hex() == '2f0c2f0d6100':
                rows.append(cur[::-1]); cur = []; a += 8
                if img[a - BASE:a - BASE + 2] == b'\x4f\xef':
                    break
            elif w == 0x4878:
                cur.append(struct.unpack('>h', img[a + 2 - BASE:a + 4 - BASE])[0]); a += 4
            elif w == 0x42A7:
                cur.append(0); a += 2
            else:
                raise SystemExit(f'port-map row at {a:#x} not as expected')
        lines.append(f'{nm}:')
        for r in rows:
            v, n = r[1:], sum(1 for x in r[1:] if x != -1)
            if len(v) != 16 or v[:n] != [v[0] + 2 * k for k in range(n)] or any(x != -1 for x in v[n:]) or not 0 < n <= 16:
                raise SystemExit('port-map row not regular')
            lines.append(f'        .byte {r[0]},{v[0]},{n}')
    open(os.path.join(PMD, 'rows.inc'), 'w').write('\n'.join(lines) + '\n')


def asm(d, src, obj):
    subprocess.run([BIN + 'm68k-elf-as', '-mcpu=5206e', '-o', obj, src], check=True, cwd=d)


def build(base, out, probe=False, slew=True, origfilt=False, name=None, nfz=0):
    with tempfile.TemporaryDirectory() as td:
        rel = os.path.join(td, 'rel.bin')
        syms_l = build_lpfuzz.build(base, rel, NAME, release=True, origfilt=origfilt, nfz=nfz)
        img = bytearray(open(rel, 'rb').read())
    F = ((syms_l['end_of_ctor'] + 1) & ~1, REGION_END)
    # ---- the holes must be what we proved ----
    for a, s in STRINGS.items():
        if img[a - BASE:a - BASE + len(s) + 1] != s + b'\0':
            raise SystemExit(f'string at {a:#x} not as proven')
    for site, tgt in PEAS.items():
        if img[site - BASE:site - BASE + 6] != b'\x48\x79' + struct.pack('>I', tgt):
            raise SystemExit(f'pea at {site:#x} not pea {tgt:#x}')
    for lo, hi in (V16, V48, U48):
        if any(u32(img, a) != DEFAULT_VEC for a in range(lo, hi, 4)):
            raise SystemExit(f'vectors {lo:#x}..{hi:#x} not all default')
    if img[F[0] - BASE:F[1] - BASE] != b'\x4e\x71' * ((F[1] - F[0]) // 2):
        raise SystemExit('filter-region tail not NOP fill')
    if u32(img, EXEC_PTR) != PASTE:
        raise SystemExit('Paste exec pointer not stock')
    m = img[MENU - BASE:MENU - BASE + 18]
    if u32(img, MENU) != 0 or u32(img, MENU + 8) != 0xA3F68 or m[16:18] != b'\x02\x12':
        raise SystemExit('menu slot 0xA4AB0 not the empty stub')
    for a, (want, _, _) in HOOKS.items():
        if img[a - BASE:a - BASE + len(want) // 2].hex() != want:
            raise SystemExit(f'hook site {a:#x} not as expected')
    if zlib.crc32(img[PM[0] - BASE:PM[1] - BASE]) != PM_CRC or (u32(img, PM_PA), u32(img, PM_PB)) != (0x15EF5C, 0x15F3E0):
        raise SystemExit('port-map builders not stock')
    if struct.unpack('>hh', img[PAN_TAB + 126 - BASE:PAN_TAB + 130 - BASE]) != PAN_FIX[0]:
        raise SystemExit('pan table entries 63/64 not stock')
    if (img[RFX_PAN - BASE:RFX_PAN + 256 - BASE] != img[PAN_TAB - BASE:PAN_TAB + 256 - BASE]
            or img[RFX_PAN_REF[0] - BASE:RFX_PAN_REF[0] + 6 - BASE].hex() != RFX_PAN_REF[1]):
        raise SystemExit('RFX pan table 0x10E794 not the stock copy of 0x61590')
    if img[HPG_CF - BASE:HPG_CF - BASE + 10].hex() != HPG_CF_STOCK or img[HPG_PQ - BASE:HPG_PQ - BASE + 6].hex() != HPG_PQ_STOCK:
        raise SystemExit('HP/BP common_cf / common_pq not as expected')
    for a in HPG_K:
        if img[a + 12 - BASE] != 0 or img[a + 15 - BASE] != 0:
            raise SystemExit(f'HP/BP descriptor {a:#x} retshift/byte 15 not 0')
    if img[SCN_NAME - BASE:SCN_NAME - BASE + 7] != b'SLpScn\0':
        raise SystemExit('destination 58 name not SLpScn')
    if img[BM_SLOT - BASE:BM_SLOT - BASE + 8] != bytes(8) or u32(img, BM_SLOT + 12) != 0xB60D8:
        raise SystemExit('Beat Munger soft-key slot not empty')
    d55 = DEST_TABLE + 8 * SLICE_CODE
    nm, off, fl = struct.unpack('>IHH', img[d55 - BASE:d55 - BASE + 8])
    if off != 0x1E or img[nm - BASE] != 0:
        raise SystemExit('destination 55 in use')
    # ---- assemble and link both patches into the holes ----
    asm(SIL, 'silence.s', 'silence.o')
    asm(SLC, 'slice.s', 'slice.o')
    asm(SLC, 'probe.s', 'probe.o')
    portmap_rows(img)
    asm(PMD, 'portmap.s', 'portmap.o')
    asm(SLR, 'slicer.s', 'slicer.o')
    asm(HPG, 'hpgain.s', 'hpgain.o')
    so, lo_, po, pm, sr, hg = 'silence.o', 'slice.o', 'probe.o', 'portmap.o', 'slicer.o', 'hpgain.o'   # linked from a temp dir (the script cannot quote paths)
    if probe:
        place = [('.blkA', A, [(lo_, '.slA')]), ('.blkB', B_, [(lo_, '.slB')]), ('.blkF', F, [(lo_, '.slF'), (lo_, '.slT'), (lo_, '.slS')]),
                 ('.blkV48', V48, [(po, '.prb'), (lo_, '.slP')]), ('.blkU', U48, [(po, '.prbio')])]
    else:
        place = [('.blkA', A, [(lo_, '.slA')]), ('.blkB', B_, [(lo_, '.slB'), (so, '.silwrap')]),
                 ('.blkC', C, [(so, '.silstr')]),
                 ('.blkF', F, [(so, '.silh'), (lo_, '.slF')] + ([] if origfilt else [(lo_, '.slT')]) + [(lo_, '.slS')]),
                 ('.blkV48', V48, [(so, '.silx1'), (lo_, '.slP')]), ('.blkU', U48, [(so, '.silx2')]),
                 ('.blkV16', V16, [(so, '.silx3')])]
    # origfilt: the ctor's filter list grows by 18 bytes, so the tick hook .slT moves from .blkF to .blkPM
    place.append(('.blkPM', PM, [(pm, '.pm')] + ([] if probe else [(sr, '.slcx')]) + [(hg, '.hpg')]
                  + ([(lo_, '.slT')] if origfilt and not probe else [])))
    ld = 'SECTIONS {\n' + ''.join(
        f'  {n} 0x{r[0]:X} : {{ ' + ' '.join(f'{o}({s})' for o, s in parts) + ' }\n' for n, r, parts in place) + '}\n'
    with tempfile.TemporaryDirectory() as td:
        import shutil
        shutil.copy(os.path.join(SIL, 'silence.o'), td)
        shutil.copy(os.path.join(SLC, 'slice.o'), td)
        shutil.copy(os.path.join(SLC, 'probe.o'), td)
        shutil.copy(os.path.join(PMD, 'portmap.o'), td)
        shutil.copy(os.path.join(SLR, 'slicer.o'), td)
        shutil.copy(os.path.join(HPG, 'hpgain.o'), td)
        open(os.path.join(td, 'beta2.ld'), 'w').write(ld)
        elf = os.path.join(td, 'beta2.elf')
        subprocess.run([BIN + 'm68k-elf-ld', '-T', 'beta2.ld', '-o', 'beta2.elf', so, lo_, pm, hg] + ([po] if probe else [sr]),
                       check=True, cwd=td)
        syms = {}
        for line in subprocess.run([BIN + 'm68k-elf-nm', elf], check=True, capture_output=True, text=True).stdout.splitlines():
            a, t, n = line.split()
            if t in 'tTdDrR':
                syms[n] = int(a, 16)
        for n, (lo, hi), _ in place:
            subprocess.run([BIN + 'm68k-elf-objcopy', '-O', 'binary', '-j', n, elf, os.path.join(td, 'sec.bin')], check=True)
            code = open(os.path.join(td, 'sec.bin'), 'rb').read()
            if len(code) > hi - lo:
                raise SystemExit(f'{n} {len(code)} > {hi - lo}')
            fill = b'\x4e\x71' * ((hi - lo) // 2) if (lo, hi) in (A, B_, C, F, PM) else None
            if fill:
                img[lo - BASE:hi - BASE] = fill
            img[lo - BASE:lo - BASE + len(code)] = code
            print(f'{n}: {len(code)}/{hi - lo} bytes at {lo:#x}')
    # ---- patches ----
    for site in PEAS:
        img[site - BASE:site - BASE + 6] = NOP_SUBQ
    if slew:
        if img[SLEW_AT - BASE:SLEW_AT - BASE + 30].hex() != SLEW_STOCK:
            raise SystemExit('tick apply code not as expected')
        sdir = os.path.join(ROOT, 'patches', 'slpscn')
        subprocess.run([BIN + 'm68k-elf-as', '-mcpu=5206e', '-o', 'slew.o', 'slew.s'], check=True, cwd=sdir)
        open(os.path.join(sdir, 'slew.ld'), 'w').write(f'SKIP = 0x5FF24;\nSECTIONS {{ .slew 0x{SLEW_AT:X} : {{ slew.o(.slew) }} }}\n')
        subprocess.run([BIN + 'm68k-elf-ld', '-T', 'slew.ld', '-o', 'slew.elf', 'slew.o'], check=True, cwd=sdir)
        subprocess.run([BIN + 'm68k-elf-objcopy', '-O', 'binary', '-j', '.slew', 'slew.elf', 'slew.bin'], check=True, cwd=sdir)
        sb = open(os.path.join(sdir, 'slew.bin'), 'rb').read()
        if len(sb) > 30:
            raise SystemExit(f'slew {len(sb)} > 30')
        img[SLEW_AT - BASE:SLEW_AT - BASE + 30] = sb + b'\x4e\x71' * ((30 - len(sb)) // 2)
        print(f'slew: {len(sb)}/30 bytes at {SLEW_AT:#x}; tick -> shift_t {syms["shift_t"]:#x}')
    if not probe:
        img[MENU - BASE:MENU - BASE + 18] = struct.pack('>IIII', syms['sil_name'], syms['sil_short'], syms['sil_key'], 0) + b'\x02\x02'
        struct.pack_into('>I', img, EXEC_PTR - BASE, syms['paste_wrap'])
    else:
        if img[DESC195 + 0x1A - BASE:DESC195 + 0x22 - BASE] != bytes(8):
            raise SystemExit('descriptor 195 getter/setter not stock')
        struct.pack_into('>II', img, DESC195 + 0x1A - BASE, syms['prb_get'], syms['prb_set'])
    for a, (want, op, target) in HOOKS.items():
        if probe and target == 'slice_exit':
            target = 'probe_in'
        new = bytes.fromhex({'jmp': '4ef9', 'jsr': '4eb9'}[op]) + struct.pack('>I', syms[target])
        new += b'\x4e\x71' * ((len(want) // 2 - len(new)) // 2)
        img[a - BASE:a - BASE + len(new)] = new
    struct.pack_into('>IHH', img, d55 - BASE, syms['name_slice'], 0x1C, 0x0100)
    if syms['pm_A'] != PM_PA_TARGET:
        raise SystemExit('pm_A not at the stock entry')
    struct.pack_into('>I', img, PM_PB - BASE, syms['pm_B'])
    img[SCN_NAME - BASE:SCN_NAME - BASE + 7] = b'WTScan\0'
    struct.pack_into('>hh', img, PAN_TAB + 126 - BASE, *PAN_FIX[1])
    main = struct.unpack('>128h', img[PAN_TAB - BASE:PAN_TAB + 256 - BASE])
    struct.pack_into('>128h', img, RFX_PAN - BASE, *[-4096 if i == 0 else (t * 105) >> 8 for i, t in enumerate(main)])
    img[HPG_CF - BASE:HPG_CF - BASE + 10] = bytes.fromhex('4eb9') + struct.pack('>I', syms['hg_cf']) + bytes.fromhex('4e714e71')
    img[HPG_PQ - BASE:HPG_PQ - BASE + 6] = bytes.fromhex('4eb9') + struct.pack('>I', syms['hg_pq'])
    for a, k in HPG_K.items():
        img[a + 15 - BASE] = k
    if not probe:
        struct.pack_into('>II', img, BM_SLOT - BASE, syms['slc_name'], syms['slc_key'])
    img[0x18:0x30] = (b'EOS 4.71-b2 SliceProbe' if probe else (name or NAME)).ljust(24, b' ')
    struct.pack_into('>II', img, 4, 0, 0xffffffff)
    c = eos_lz.csum(img)
    struct.pack_into('>II', img, 4, c, c ^ 0xffffffff)
    open(out, 'wb').write(img)
    json.dump(dict(syms, filter_tail=F[0], pm_free=syms['pm_end']), open(out + '.syms.json', 'w'), indent=1)
    print(f'{out}: checksum {c:08x}; name {(name or NAME).decode()!r}')
    build.syms_l = syms_l
    return syms, F


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2], probe='--probe' in sys.argv, slew='--noslew' not in sys.argv,
          origfilt='--origfilt' in sys.argv)
